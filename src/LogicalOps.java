public class LogicalOps {
    public static void main(String[] args) {
        boolean x = true;
        boolean y = false;

        System.out.println("x && y = " + (x && y)); // AND
        System.out.println("x || y = " + (x || y)); // OR
        System.out.println("!x = " + (!x));         // NOT
        System.out.println("x ^ y = " + (x ^ y));   // XOR
    }
}
